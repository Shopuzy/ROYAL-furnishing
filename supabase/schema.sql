-- 2. TABLES

-- Authorized Administrator Whitelist (linked to Supabase Auth users)
CREATE TABLE IF NOT EXISTS public.admin_users (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL UNIQUE,
  name text NOT NULL DEFAULT 'Administrator',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Product Categories
CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Products Catalog
CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  category_id bigint NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  description text NOT NULL DEFAULT '',
  images_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  specifications_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  colors_designs_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  price numeric(12,2) DEFAULT NULL,
  price_unit text DEFAULT NULL,
  stock_status text NOT NULL DEFAULT 'In Stock'
    CHECK (stock_status IN ('In Stock', 'Low Stock', 'Made to Order', 'Out of Stock')),
  availability_type text NOT NULL DEFAULT 'Both'
    CHECK (availability_type IN ('Both', 'Retail', 'Wholesale')),
  is_published boolean NOT NULL DEFAULT true,
  featured boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Customer Enquiries (Protected: Public can submit via RPC only; Admin can read/manage)
CREATE TABLE IF NOT EXISTS public.enquiries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_code text NOT NULL UNIQUE,
  customer_name text NOT NULL,
  mobile_number text NOT NULL,
  email text DEFAULT NULL,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL DEFAULT '',
  category_name text NOT NULL DEFAULT '',
  quantity text NOT NULL DEFAULT '',
  enquiry_type text NOT NULL DEFAULT 'Retail'
    CHECK (enquiry_type IN ('Retail', 'Wholesale')),
  delivery_location text NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'New'
    CHECK (status IN ('New', 'Contacted', 'Quotation Sent', 'Converted to Order', 'Closed')),
  internal_notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Customer Orders & Quotation Requests (Never marked Confirmed until Admin updates status)
CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code text NOT NULL UNIQUE,
  enquiry_id bigint REFERENCES public.enquiries(id) ON DELETE SET NULL,
  customer_name text NOT NULL,
  mobile_number text NOT NULL,
  email text DEFAULT NULL,
  delivery_location text NOT NULL DEFAULT '',
  items_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  order_type text NOT NULL DEFAULT 'Retail'
    CHECK (order_type IN ('Retail', 'Wholesale')),
  total_amount numeric(12,2) DEFAULT NULL,
  status text NOT NULL DEFAULT 'New'
    CHECK (status IN ('New', 'Contacted', 'Quotation Sent', 'Confirmed', 'Processing', 'Completed', 'Cancelled')),
  notes text NOT NULL DEFAULT '',
  confirmed_at timestamptz DEFAULT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

