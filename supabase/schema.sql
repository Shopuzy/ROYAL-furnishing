-- 5. ADMIN AUTHORIZATION HELPER FUNCTION
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.admin_users
    WHERE user_id = auth.uid()
      AND is_active = true
  );
$$;

-- 6. SECURE PUBLIC SUBMISSION RPCs (Allows customers to submit without exposing SELECT on enquiries/orders)
CREATE OR REPLACE FUNCTION public.submit_public_enquiry(
  p_customer_name text,
  p_mobile_number text,
  p_email text DEFAULT NULL,
  p_product_id bigint DEFAULT NULL,
  p_product_name text DEFAULT 'General Enquiry',
  p_category_name text DEFAULT 'General',
  p_quantity text DEFAULT '',
  p_enquiry_type text DEFAULT 'Retail',
  p_delivery_location text DEFAULT '',
  p_message text DEFAULT ''
)
RETURNS public.enquiries
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_code text;
  v_type text;
  v_created public.enquiries;
  v_count bigint;
BEGIN
  IF length(trim(coalesce(p_customer_name, ''))) < 2 THEN
    RAISE EXCEPTION 'Please enter your full name.';
  END IF;

  IF length(regexp_replace(coalesce(p_mobile_number, ''), '[^0-9+]', '', 'g')) < 7 THEN
    RAISE EXCEPTION 'Please provide a valid mobile number.';
  END IF;

  IF trim(coalesce(p_quantity, '')) = '' THEN
    RAISE EXCEPTION 'Please specify required quantity or area.';
  END IF;

  IF trim(coalesce(p_delivery_location, '')) = '' THEN
    RAISE EXCEPTION 'Please enter the delivery city or location.';
  END IF;

  v_type := CASE WHEN p_enquiry_type = 'Wholesale' THEN 'Wholesale' ELSE 'Retail' END;

  SELECT count(*) INTO v_count FROM public.enquiries;
  v_code := 'RF-ENQ-' || extract(year FROM now())::int::text || '-' || (v_count + 1001)::text || lpad((floor(random() * 90) + 10)::int::text, 2, '0');

  INSERT INTO public.enquiries (
    enquiry_code, customer_name, mobile_number, email, product_id,
    product_name, category_name, quantity, enquiry_type, delivery_location,
    message, status, internal_notes
  ) VALUES (
    v_code,
    trim(p_customer_name),
    trim(p_mobile_number),
    nullif(trim(coalesce(p_email, '')), ''),
    p_product_id,
    coalesce(nullif(trim(p_product_name), ''), 'General Enquiry'),
    coalesce(nullif(trim(p_category_name), ''), 'General'),
    trim(p_quantity),
    v_type,
    trim(p_delivery_location),
    trim(coalesce(p_message, '')),
    'New',
    ''
  )
  RETURNING * INTO v_created;

  RETURN v_created;
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_public_order(
  p_customer_name text,
  p_mobile_number text,
  p_email text DEFAULT NULL,
  p_delivery_location text DEFAULT '',
  p_order_type text DEFAULT 'Retail',
  p_notes text DEFAULT '',
  p_items jsonb DEFAULT '[]'::jsonb
)
RETURNS public.orders
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_code text;
  v_type text;
  v_created public.orders;
  v_count bigint;
BEGIN
  IF length(trim(coalesce(p_customer_name, ''))) < 2 THEN
    RAISE EXCEPTION 'Please enter your full name.';
  END IF;

  IF length(regexp_replace(coalesce(p_mobile_number, ''), '[^0-9+]', '', 'g')) < 7 THEN
    RAISE EXCEPTION 'Please provide a valid mobile number.';
  END IF;

  IF trim(coalesce(p_delivery_location, '')) = '' THEN
    RAISE EXCEPTION 'Please provide a delivery location.';
  END IF;

  IF jsonb_typeof(coalesce(p_items, '[]'::jsonb)) <> 'array' OR jsonb_array_length(coalesce(p_items, '[]'::jsonb)) = 0 THEN
    RAISE EXCEPTION 'Please include at least one material item in your quotation request.';
  END IF;

  v_type := CASE WHEN p_order_type = 'Wholesale' THEN 'Wholesale' ELSE 'Retail' END;

  SELECT count(*) INTO v_count FROM public.orders;
  v_code := 'RF-ORD-' || extract(year FROM now())::int::text || '-' || (v_count + 1001)::text || lpad((floor(random() * 90) + 10)::int::text, 2, '0');

  INSERT INTO public.orders (
    order_code, enquiry_id, customer_name, mobile_number, email,
    delivery_location, items_json, order_type, total_amount, status, notes, confirmed_at
  ) VALUES (
    v_code,
    NULL,
    trim(p_customer_name),
    trim(p_mobile_number),
    nullif(trim(coalesce(p_email, '')), ''),
    trim(p_delivery_location),
    p_items,
    v_type,
    NULL,
    'New',
    trim(coalesce(p_notes, '')),
    NULL
  )
  RETURNING * INTO v_created;

  RETURN v_created;
END;
$$;

